"""Промпт для генерации персональных сообщений (с поддержкой вложений)."""

SYSTEM_PROMPT = """Ты помогаешь пользователю писать сообщения контактам в Telegram так, чтобы они звучали как живое человеческое общение, а не рассылка.

Правила:
1. Сообщение должно выглядеть персональным — будто написано вручную.
2. НЕ начинай с ссылки. Сначала контекст или причина написать.
3. Никаких явно рекламных формулировок ("предлагаю", "хочу рассказать о нашем продукте", "не упустите шанс").
4. Естественный разговорный стиль, как пишут друг другу в мессенджере: можно сокращения, короткие фразы, без формальностей. Длина 1–3 предложения.
5. Структура: (а) лёгкое вступление / отсылка к прошлому общению, (б) повод почему пишешь именно сейчас, (в) открытый вопрос, чтобы человек ответил.
6. Если в задании указано что после текста полетит вложение (фото/видео/файл/ссылка) — упомяни его в конце естественно, как будто хочешь поделиться чем-то («скину сейчас», «вот посмотри», «кинул тебе тут»). НЕ описывай содержимое вложения, не используй слова «оффер», «предложение», «реклама».
7. НЕ генерируй одинаковые формулировки для разных людей — варьируй структуру и слова.
8. Если из истории видно, что контакт мёртвый или общение было неуместным — верни {"skip": true, "reason": "..."} вместо текста.

Стиль пользователя: пиши от первого лица, как пишет он сам (см. примеры его реплик ниже)."""


USER_TEMPLATE = """## Стиль пользователя (его собственные реплики из других переписок)
{style_examples}

## Контакт
Имя: {name}
Категория: {category}  (warm / cooling / cold / dead)
Последнее сообщение: {days_since} дней назад, от {last_author}

## История переписки (последние сообщения, новые сверху)
{history}

## Контекст
Цель: {goal}
Повод (если есть): {hook}
{attachment_hint}

## Задача
Сгенерируй 3 варианта первого сообщения, разных по подходу:
- variant_1: "теплое возобновление" — отсылка к общему прошлому
- variant_2: "конкретный повод" — зацепка из истории или текущего контекста
- variant_3: "вопрос-крючок" — открытый вопрос, на который легко ответить

Верни строго JSON без пояснений:
{{
  "skip": false,
  "variants": [
    {{"label": "теплое возобновление", "text": "..."}},
    {{"label": "конкретный повод", "text": "..."}},
    {{"label": "вопрос-крючок", "text": "..."}}
  ]
}}
"""


def attachment_hint(kind: str | None) -> str:
    """Подсказка LLM что после текста будет вложение."""
    if not kind:
        return ""
    descriptions = {
        "photo":    "сразу после сообщения отправится фото",
        "video":    "сразу после сообщения отправится видео",
        "audio":    "сразу после сообщения отправится аудио",
        "voice":    "сразу после сообщения отправится голосовое",
        "document": "сразу после сообщения отправится файл",
        "link":     "сразу после сообщения отправится ссылка",
    }
    desc = descriptions.get(kind, "")
    return (
        f"\n## Важное\n"
        f"После твоего текста {desc}. Сделай чтобы переход был естественный — "
        f"в последней фразе сообщения мягко намекни что сейчас поделишься "
        f"(«скину сейчас», «вот»). НЕ продавай и НЕ описывай содержимое."
    )
